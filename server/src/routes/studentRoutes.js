import express from "express";
import * as controller from "../controllers/studentController.js";
import { authenticate } from "../middleware/authenticate.js";
import { authorize } from "../middleware/authorize.js";
import { validate } from "../middleware/validate.js";
import { createStudentSchema, resetPasswordSchema, studentListSchema, updateStudentSchema } from "../validators/managementValidators.js";
const router = express.Router();
router.use(authenticate, authorize("admin", "teacher"));
router.get("/", validate(studentListSchema), controller.list);
router.post("/", validate(createStudentSchema), controller.create);
router.patch("/:studentId", validate(updateStudentSchema), controller.update);
router.post("/:studentId/reset-password", validate(resetPasswordSchema), controller.resetPassword);
export default router;
