import express from "express";
import * as controller from "../controllers/assignmentController.js";
import { authenticate } from "../middleware/authenticate.js";
import { authorize } from "../middleware/authorize.js";
import { validate } from "../middleware/validate.js";
import { assignmentListSchema, createAssignmentSchema, updateAssignmentSchema } from "../validators/managementValidators.js";
const router = express.Router();
router.use(authenticate, authorize("admin", "teacher"));
router.get("/", validate(assignmentListSchema), controller.list);
router.post("/", validate(createAssignmentSchema), controller.create);
router.patch("/:assignmentId", validate(updateAssignmentSchema), controller.update);
router.delete("/:assignmentId", controller.remove);
export default router;
